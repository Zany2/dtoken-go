package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

const (
	sourcePackage   = "gin"
	generatedHeader = "// Code generated by integrationexportgen; DO NOT EDIT.\n"
)

var exportFiles = []string{"error_export.go", "export.go"}

var targetPackages = []string{"beego", "chi", "echo", "fiber", "gf", "hertz", "kratos"}

func main() {
	checkOnly := flag.Bool("check", false, "verify repository exports without writing / 只检查仓库导出，不写文件")
	flag.Parse()
	for _, exportFile := range exportFiles {
		source, err := os.ReadFile(exportFile)
		if err != nil {
			fail("read canonical "+exportFile, err)
		}

		for _, packageName := range targetPackages {
			output, err := render(source, packageName)
			if err != nil {
				fail("render "+packageName+" "+exportFile, err)
			}

			targetPath := filepath.Join("..", packageName, exportFile)
			if err = writeOrCheck(targetPath, output, *checkOnly); err != nil {
				fail("write "+targetPath, err)
			}
		}
	}
}

// render creates one framework export file from a Gin canonical source. render 根据 Gin 标准源生成单个框架导出文件。
func render(source []byte, packageName string) ([]byte, error) {
	// Windows checkouts must match the same newline-sensitive anchors as Unix sources. Windows 检出文件须与 Unix 源文件匹配相同的换行敏感锚点。
	text := strings.ReplaceAll(string(source), "\r\n", "\n")
	packageClause := "package " + sourcePackage
	packageIndex := strings.Index(text, packageClause)
	if packageIndex < 0 {
		return nil, fmt.Errorf("canonical package clause %q not found", packageClause)
	}

	// Drop source-only author and go:generate comments. 丢弃仅属于标准源的作者和 go:generate 注释。
	text = generatedHeader + text[packageIndex:]
	var err error
	text, err = replaceExactlyOnce(text, packageClause, "package "+packageName)
	if err != nil {
		return nil, err
	}

	formatted, err := format.Source([]byte(text))
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return formatted, nil
}

func replaceExactlyOnce(text, old, replacement string) (string, error) {
	if count := strings.Count(text, old); count != 1 {
		return "", fmt.Errorf("replacement anchor occurs %d times: %q", count, old)
	}
	return strings.Replace(text, old, replacement, 1), nil
}

func writeOrCheck(path string, output []byte, checkOnly bool) error {
	current, err := os.ReadFile(path)
	if checkOnly {
		if err != nil {
			return err
		}
		if strings.ReplaceAll(string(current), "\r\n", "\n") != string(output) {
			return fmt.Errorf("generated export is out of date: %s; run go generate in integrations/gin", path)
		}
		return nil
	}
	if err == nil && string(current) == string(output) {
		return nil
	}
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	return os.WriteFile(path, output, 0o644)
}

func fail(action string, err error) {
	_, _ = fmt.Fprintf(os.Stderr, "integrationexportgen: %s: %v\n", action, err)
	os.Exit(1)
}
